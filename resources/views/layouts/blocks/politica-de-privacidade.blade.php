              <article class="privacy-section" id="responsavel">
                  <h2>Quem é responsável pelo tratamento de dados?</h2>
                  <p>Somos os controladores dos dados pessoais de nossos clientes. Isso significa que, ao optar por nossos serviços, solicitamos algumas informações e tomamos decisões para oferecer o melhor e mais seguro serviço possível.</p>
                  <p>Como operadores, tratamos dados pessoais de terceiros inseridos nas nossas soluções pelos clientes, seguindo as decisões destes que atuam como controladores.</p>
                  <p>Além disso, a DIGIFY pode contar com operadores terceiros, como assessoria jurídica e parceiros tecnológicos, para auxiliar no tratamento de dados.</p>
                  <p>É importante lembrar que o WhatsApp e outros canais são independentes e não possuem vínculo com este documento. Por isso, recomendamos que você leia os termos de uso e políticas de privacidade dessas plataformas antes de utilizar nossos serviços.</p>
              </article>

              <article class="privacy-section" id="seguranca">
                  <h2>Como garantimos a segurança de seus dados?</h2>
                  <p>Na DIGIFY, a segurança dos seus dados pessoais é uma prioridade. Implementamos todas as medidas sugeridas pela Autoridade Nacional de Proteção de Dados (ANPD), conforme o Guia Orientativo para Agentes de Tratamento de Pequeno Porte. Essas práticas incluem tecnologias e procedimentos que ajudam a proteger suas informações.</p>
                  <p>Para garantir um ambiente seguro, utilizamos os servidores da Amazon Web Services e DigitalOcean, cujo acesso é restrito. Esses servidores podem envolver a transferência internacional de dados para os Estados Unidos, onde estão localizados.</p>
              </article>

              <article class="privacy-section" id="dados-necessarios">
                  <h2>Quais dados são necessários para utilizar nossa plataforma?</h2>
                  <p>Para cadastro e uso dos nossos serviços, solicitamos:</p>
                  <ul>
                      <li>Usuário colaborador: nome e CPF.</li>
                      <li>Usuário administrador: nome, CPF, e-mail, marca da empresa, razão social, endereço e telefone.</li>
                  </ul>
              </article>

              <article class="privacy-section" id="finalidades">
                  <h2>Para quais finalidades utilizamos seus dados pessoais?</h2>
                  <p>Tratamos seus dados de acordo com a Lei Geral de Proteção de Dados Pessoais para as seguintes finalidades:</p>
                  <ul>
                      <li>Prestar serviços.</li>
                      <li>Dar suporte e realizar atendimento ao cliente.</li>
                      <li>Enviar comunicações de vendas e marketing.</li>
                      <li>Oferecer nossos produtos e serviços.</li>
                  </ul>
              </article>

              <article class="privacy-section" id="compartilhamento">
                  <h2>Com quem compartilhamos seus dados pessoais?</h2>
                  <p>Não compartilhamos seus dados com terceiros, exceto nos casos indicados em nosso Aviso de Privacidade, mediante consentimento do titular ou por exigência legal/judicial.</p>
              </article>

              <article class="privacy-section" id="registros-acesso">
                  <h2>Seus registros de acesso serão coletados?</h2>
                  <p>Sim, coletamos registros de acesso, incluindo data e hora de uso da plataforma a partir de um endereço IP específico. Esses registros são armazenados com sigilo por, no mínimo, seis meses, conforme a Lei n.º 12.965/2014 e a Lei n.º 13.709/18.</p>
              </article>

              <article class="privacy-section" id="coleta-indireta">
                  <h2>Dados pessoais serão coletados de forma indireta?</h2>
                  <p>Sim, além dos registros de acesso, algumas informações podem ser coletadas indiretamente, de acordo com nossa Política de Cookies.</p>
              </article>

              <article class="privacy-section" id="comunicacoes">
                  <h2>Registros de comunicações serão armazenados?</h2>
                  <p>Armazenamos as conversas realizadas em nossos canais de comunicação para melhorar e tornar o atendimento mais eficiente. Sem esse histórico, seria necessário repetir informações sempre que você entrasse em contato.</p>
              </article>

              <article class="privacy-section" id="direitos">
                  <h2>Quais são os seus direitos como usuário?</h2>
                  <p>Você tem o direito de, a qualquer momento, solicitar:</p>
                  <ul>
                      <li>Confirmação da existência de tratamento de dados.</li>
                      <li>Acesso aos seus dados.</li>
                      <li>Correção de dados incompletos ou desatualizados.</li>
                      <li>Anonimização, bloqueio ou eliminação de dados desnecessários ou tratados fora da Lei.</li>
                      <li>Portabilidade dos dados a outro fornecedor.</li>
                      <li>Eliminação de dados tratados com consentimento, exceto quando exigido por lei.</li>
                      <li>Informações sobre com quem a DIGIFY compartilhou seus dados.</li>
                      <li>Informações sobre a possibilidade de não fornecer consentimento e suas consequências.</li>
                      <li>Revogação do consentimento.</li>
                  </ul>
              </article>

