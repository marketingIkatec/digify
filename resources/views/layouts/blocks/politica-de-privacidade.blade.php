              <article class="privacy-section" id="introducao">
                  <h2>Introdução</h2>
                  <p>Abaixo, destacamos os principais pontos, que você pode conferir de maneira mais detalhada em nosso Aviso de Privacidade.</p>
                  <p>Estamos sempre disponíveis para esclarecer suas dúvidas pelo e-mail <a href="mailto:digify@ikatec.com.br">digify@ikatec.com.br</a>.</p>
                  <p>Para questões específicas sobre seus dados pessoais, entre em contato pelo e-mail <a href="mailto:encarregado@ikatec.com.br">encarregado@ikatec.com.br</a>.</p>
